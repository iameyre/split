/** "013 國泰世華" */
export function bankLabel(bank) {
  return `${bank[0]} ${bank[1]}`;
}

/** 依輸入的代碼或名稱找銀行，最多回傳 limit 筆 */
export function searchBanks(query, limit = 6) {
  const q = String(query || '').normalize('NFKC').trim().toLowerCase();
  if (!q) return [];
  const exactCode = BANKS.filter((b) => b[0] === q);
  const byCode = BANKS.filter((b) => b[0].startsWith(q) && b[0] !== q);
  const byName = BANKS.filter((b) => !b[0].startsWith(q)
    && b.slice(1).some((n) => n.toLowerCase().includes(q)));
  return [...exactCode, ...byCode, ...byName].slice(0, limit);
}

/** 只打代碼（例如 "013"）就展開成 "013 國泰世華"；其他情況原樣回傳 */
export function expandBankCode(value) {
  const v = String(value || '').trim();
  const hit = BANKS.find((b) => b[0] === v);
  return hit ? bankLabel(hit) : v;
}
